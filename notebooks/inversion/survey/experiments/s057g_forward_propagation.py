"""s057g — forward-propagation discrimination on seed 89.

Architecture: for each candidate (q_a, ω) — generated by single-pair finite-
diff at anchor Δ_gen and filtered by |ω|-prior — propagate q_a forward via
const-ω quaternion exponential to each validator epoch t_v, and check
whether the propagated q lands within HIT_THRESHOLD_DEG of any survivor
in C_{t_v}. Score per candidate = Σ_v weight_v · indicator(hit).

Weight = log(100k / |C_v|). Small clouds (rare survivors) score 7+;
large clouds (common survivors) score ~3.

Smoke test FIRST: propagate q_truth(t_a) using truth-ω and measure
deviation from cached q_truth(t_a+Δ). Determines const-ω validity
range. Within that range, all small-cloud epochs become validators.

Discrimination test: where does the candidate closest to (truth_q_a,
truth_ω) rank by score? If top 1% → architecture works.
"""

from __future__ import annotations

import json
from pathlib import Path

import matplotlib.pyplot as plt
import numpy as np
from scipy.spatial.transform import Rotation

SURVEY = Path(__file__).resolve().parents[1]
DENSE_RUN = SURVEY / "results" / "s048c_cloud_viewer" / "seed089" / "8bb9b81f1602" / "spread.npz"
TRAJ089 = SURVEY / "data" / "trajectories" / "traj_seed089.npz"
OUT = SURVEY / "results" / "s057g_forward_propagation"
OUT.mkdir(parents=True, exist_ok=True)

T_A = 411
DELTA_GEN = 15
PRIOR_BRACKET = (0.75, 1.25)
HIT_THRESHOLD_DEG = 5.0
SMOKE_DELTAS = [1, 2, 3, 5, 7, 10, 15, 20, 30, 50, 80]
CONST_OMEGA_RELIABLE_MAX_DEG = 20.0


def wxyz_to_xyzw(q):
    return q[..., [1, 2, 3, 0]]


def xyzw_to_wxyz(q):
    return q[..., [3, 0, 1, 2]]


def fd_omega_passive(q_a, q_b, dt):
    R_a = Rotation.from_quat(wxyz_to_xyzw(q_a))
    R_b = Rotation.from_quat(wxyz_to_xyzw(q_b))
    return (R_b * R_a.inv()).as_rotvec() / dt


def propagate_const_omega(q_a, omega_rad_s, dt):
    """q_b = exp(ω·dt) ⊗ q_a (passive). Broadcasts."""
    rotvec = omega_rad_s * dt
    R_om = Rotation.from_rotvec(rotvec)
    R_a = Rotation.from_quat(wxyz_to_xyzw(q_a))
    return xyzw_to_wxyz((R_om * R_a).as_quat())


def quat_ang_deg(q1, q2):
    """Geodesic angle between two unit quats in degrees (axis-equivalent)."""
    return float(2 * np.degrees(np.arccos(
        np.clip(abs(np.dot(q1, q2)), 0, 1))))


def main() -> dict:
    z = np.load(DENSE_RUN)
    survive_all = z["survive_all"]
    q_pool = z["q_pool_wxyz"]
    obs_times = z["obs_times"]

    traj = np.load(TRAJ089)
    q_truth_t = traj["quaternions"]

    dt_epoch = float(np.median(np.diff(obs_times)))
    n_epochs = len(survive_all)

    # === STEP 1: SMOKE TEST const-ω accuracy ===
    print("=== const-ω propagation accuracy on seed 89 ===")
    # ω at t_a from finite-diff of truth quaternions over Δ=1 epoch (instantaneous)
    om_inst = fd_omega_passive(q_truth_t[T_A:T_A+1],
                                q_truth_t[T_A+1:T_A+2], dt_epoch)[0]
    om_inst_mag_dps = float(np.linalg.norm(om_inst)) * 180 / np.pi
    print(f"  instantaneous truth-ω at t_a (Δ=1 finite-diff): {om_inst_mag_dps:.4f} dps")

    smoke = []
    for Δ in SMOKE_DELTAS:
        if T_A + Δ >= n_epochs:
            continue
        q_pred = propagate_const_omega(q_truth_t[T_A], om_inst, Δ * dt_epoch)
        q_act = q_truth_t[T_A + Δ]
        err = quat_ang_deg(q_pred, q_act)
        smoke.append({"delta": Δ, "delta_s": Δ * dt_epoch, "err_deg": err})
        print(f"  Δ={Δ:3d} ({Δ*dt_epoch:5.1f}s): const-ω predicted q vs cached q = {err:.2f}°")

    # Validator range: keep going while const-ω error < CONST_OMEGA_RELIABLE_MAX_DEG
    valid_max_delta = 1
    for r in smoke:
        if r["err_deg"] <= CONST_OMEGA_RELIABLE_MAX_DEG:
            valid_max_delta = r["delta"]
        else:
            break
    print(f"  → const-ω reliable up to Δ = {valid_max_delta} epochs (err ≤ {CONST_OMEGA_RELIABLE_MAX_DEG}°)")

    # === STEP 2: VALIDATOR SELECTION ===
    # All epochs within ±valid_max_delta of T_A (excluding T_A itself).
    # Weight = log(100k/|C_v|) — small clouds are rarer, more discriminating.
    validators = []
    lo_v = max(0, T_A - valid_max_delta)
    hi_v = min(n_epochs, T_A + valid_max_delta + 1)
    for t_v in range(lo_v, hi_v):
        if t_v == T_A:
            continue
        idx_v = np.where(survive_all[t_v])[0]
        if len(idx_v) == 0:
            continue
        validators.append({
            "t_v": t_v,
            "delta": t_v - T_A,
            "C_v": q_pool[idx_v],
            "n_surv": int(len(idx_v)),
            "weight": float(np.log(100000.0 / len(idx_v))),
        })
    n_v = len(validators)
    if n_v == 0:
        raise RuntimeError("No validators in range")
    cv_sizes = [v["n_surv"] for v in validators]
    print(f"\n=== validators ===")
    print(f"  {n_v} epochs in window [t_a-{valid_max_delta}, t_a+{valid_max_delta}] excluding t_a")
    print(f"  |C_v| range: [{min(cv_sizes)}, {max(cv_sizes)}], median {int(np.median(cv_sizes))}")
    print(f"  weight range: [{min(v['weight'] for v in validators):.2f}, "
          f"{max(v['weight'] for v in validators):.2f}]")
    sum_weights = float(sum(v["weight"] for v in validators))
    print(f"  total weight (max possible score): {sum_weights:.2f}")

    # === STEP 3: CANDIDATE GENERATION ===
    idx_a = np.where(survive_all[T_A])[0]
    C_a = q_pool[idx_a]
    n_a = len(C_a)
    Δgen_t_b = T_A + DELTA_GEN
    idx_b = np.where(survive_all[Δgen_t_b])[0]
    C_b = q_pool[idx_b]
    n_b = len(C_b)
    Δt_gen = DELTA_GEN * dt_epoch
    print(f"\n=== candidate generation at Δ_gen={DELTA_GEN} ({Δt_gen:.1f}s) ===")
    print(f"  |C_a|={n_a}, |C_b|={n_b}, total pairs={n_a*n_b}")

    om_truth = fd_omega_passive(q_truth_t[T_A:T_A+1],
                                 q_truth_t[Δgen_t_b:Δgen_t_b+1], Δt_gen)[0]
    om_truth_mag = float(np.linalg.norm(om_truth))
    print(f"  truth |ω| at t_a over Δ_gen: {om_truth_mag*180/np.pi:.4f} dps")

    Q_A = np.repeat(C_a, n_b, axis=0)
    Q_B = np.tile(C_b, (n_a, 1))
    om_all = fd_omega_passive(Q_A, Q_B, Δt_gen)
    om_mag_all = np.linalg.norm(om_all, axis=1)
    target = om_truth_mag
    mask = (om_mag_all >= target * PRIOR_BRACKET[0]) & \
           (om_mag_all <= target * PRIOR_BRACKET[1])
    n_cand = int(mask.sum())
    Q_A_pass = Q_A[mask]
    om_pass = om_all[mask]
    om_mag_pass = om_mag_all[mask]
    print(f"  candidates after |ω|-prior ±25%: {n_cand}")

    # diagnostic: per-candidate distances to truth-q_a and truth-ω
    qa_dist = 2 * np.degrees(np.arccos(np.clip(
        np.abs(Q_A_pass @ q_truth_t[T_A]), 0, 1)))
    om_hat_pass = om_pass / np.linalg.norm(om_pass, axis=1, keepdims=True)
    om_truth_hat = om_truth / om_truth_mag
    om_dist = np.degrees(np.arccos(np.clip(
        np.abs(om_hat_pass @ om_truth_hat), 0, 1)))

    # truth candidate = candidate with min (qa_dist + om_dist)
    combined = qa_dist + om_dist
    truth_idx = int(np.argmin(combined))
    print(f"  truth-candidate (min qa_dist + om_dist):")
    print(f"    qa_dist = {qa_dist[truth_idx]:.2f}°,  ω_dist = {om_dist[truth_idx]:.2f}°,  "
          f"|ω| = {np.linalg.norm(om_pass[truth_idx])*180/np.pi:.4f} dps")

    # === STEP 4: FORWARD-PROPAGATION + SCORING ===
    print(f"\n=== forward-propagating {n_cand} candidates to {n_v} validators ===")
    scores = np.zeros(n_cand)
    hit_counts = np.zeros(n_cand, dtype=int)
    min_dist_per_v = np.zeros((n_cand, n_v))  # for diagnostic
    for vi, v in enumerate(validators):
        Δ = v["delta"]
        Δt = Δ * dt_epoch
        q_pred = propagate_const_omega(Q_A_pass, om_pass, Δt)  # (n_cand, 4)
        dots = np.abs(q_pred @ v["C_v"].T)                      # (n_cand, |C_v|)
        max_dot = dots.max(axis=1)
        min_ang = 2 * np.degrees(np.arccos(np.clip(max_dot, 0, 1)))
        min_dist_per_v[:, vi] = min_ang
        hit_mask = min_ang < HIT_THRESHOLD_DEG
        scores += v["weight"] * hit_mask
        hit_counts += hit_mask.astype(int)

    # null expectation: random q hit prob at threshold X = 1 - cos(X°)/2 (per cap)
    # then × |C_v|/100k roughly
    null_score_exp = 0.0
    cap_frac = 1.0 - np.cos(np.radians(HIT_THRESHOLD_DEG))
    for v in validators:
        p_hit = min(cap_frac * v["n_surv"] / 100000.0, 1.0)
        null_score_exp += v["weight"] * p_hit

    # === STEP 5: RANKING & DIAGNOSTICS ===
    rank_truth = int((scores > scores[truth_idx]).sum())
    truth_score = scores[truth_idx]
    truth_hits = int(hit_counts[truth_idx])
    print(f"\n=== ranking ===")
    print(f"  truth candidate: score = {truth_score:.2f}, hits = {truth_hits}/{n_v}")
    print(f"  rank: {rank_truth+1} of {n_cand} ({(rank_truth+1)/n_cand*100:.2f}%-ile)")
    print(f"  null expectation (random q hit): score ≈ {null_score_exp:.2f}, hit rate ≈ "
          f"{null_score_exp/sum_weights*100:.2f}% per validator")
    print(f"  score range: [{scores.min():.2f}, {scores.max():.2f}], median {np.median(scores):.2f}")

    # Top-K candidates
    top_K = 20
    top_idx = np.argsort(-scores)[:top_K]
    print(f"\n  Top {top_K} candidates:")
    for r, ti in enumerate(top_idx):
        is_truth = "← TRUTH" if ti == truth_idx else ""
        print(f"    rank {r+1:2d}: score={scores[ti]:5.2f} hits={hit_counts[ti]:2d}/{n_v}  "
              f"qa_d={qa_dist[ti]:5.2f}°  ω_d={om_dist[ti]:5.2f}°  "
              f"|ω|={np.linalg.norm(om_pass[ti])*180/np.pi:.3f}dps  {is_truth}")

    # === FIGURE ===
    fig, axes = plt.subplots(2, 2, figsize=(13, 10))

    ax = axes[0, 0]
    Δs = [r["delta"] for r in smoke]
    errs = [r["err_deg"] for r in smoke]
    ax.semilogy(Δs, errs, "bo-")
    ax.axhline(CONST_OMEGA_RELIABLE_MAX_DEG, ls="--", color="r",
               label=f"reliability cap {CONST_OMEGA_RELIABLE_MAX_DEG}°")
    ax.axvline(valid_max_delta, ls=":", color="g",
               label=f"valid_max_Δ = {valid_max_delta}")
    ax.set_xlabel("Δ epochs")
    ax.set_ylabel("const-ω predicted q vs truth q (deg, log)")
    ax.set_title("smoke test — const-ω propagation accuracy from truth")
    ax.legend(loc="best", fontsize=9)
    ax.grid(alpha=0.3, which="both")

    ax = axes[0, 1]
    ax.hist(scores, bins=40, color="lightblue", edgecolor="grey", alpha=0.8,
            label=f"all candidates (n={n_cand})")
    ax.axvline(scores[truth_idx], color="red", lw=2,
               label=f"truth candidate ({truth_score:.2f})")
    ax.axvline(null_score_exp, color="black", ls="--", lw=1,
               label=f"null E[score] ({null_score_exp:.2f})")
    ax.axvline(sum_weights, color="green", ls=":", lw=1,
               label=f"max possible ({sum_weights:.2f})")
    ax.set_xlabel("forward-prop score")
    ax.set_ylabel("# candidates")
    ax.set_title(f"score distribution; truth ranks {rank_truth+1}/{n_cand} "
                 f"({(rank_truth+1)/n_cand*100:.2f}%-ile)")
    ax.legend(loc="best", fontsize=8)

    ax = axes[1, 0]
    ax.scatter(qa_dist, scores, s=4, alpha=0.3, color="b")
    ax.scatter([qa_dist[truth_idx]], [scores[truth_idx]], s=200, marker="*",
               color="red", edgecolor="black", zorder=10, label="truth candidate")
    ax.set_xlabel("q_a distance to truth_q_a (deg)")
    ax.set_ylabel("forward-prop score")
    ax.set_title("score vs q_a-truth distance")
    ax.legend(loc="best", fontsize=9)
    ax.grid(alpha=0.3)

    ax = axes[1, 1]
    ax.scatter(om_dist, scores, s=4, alpha=0.3, color="b")
    ax.scatter([om_dist[truth_idx]], [scores[truth_idx]], s=200, marker="*",
               color="red", edgecolor="black", zorder=10, label="truth candidate")
    ax.set_xlabel("ω distance to truth-ω (deg)")
    ax.set_ylabel("forward-prop score")
    ax.set_title("score vs ω-truth distance")
    ax.legend(loc="best", fontsize=9)
    ax.grid(alpha=0.3)

    plt.tight_layout()
    fig_p = OUT / "forward_propagation.png"
    plt.savefig(fig_p, dpi=120, bbox_inches="tight")
    plt.close()
    print(f"\nSaved: {fig_p}")

    summary = {
        "seed": 89,
        "T_A": T_A,
        "delta_gen": DELTA_GEN,
        "prior_bracket": list(PRIOR_BRACKET),
        "hit_threshold_deg": HIT_THRESHOLD_DEG,
        "valid_max_delta": valid_max_delta,
        "n_validators": n_v,
        "sum_weights": sum_weights,
        "smoke_test": smoke,
        "n_candidates": n_cand,
        "truth_candidate": {
            "qa_dist_deg": float(qa_dist[truth_idx]),
            "om_dist_deg": float(om_dist[truth_idx]),
            "om_mag_dps": float(np.linalg.norm(om_pass[truth_idx]) * 180 / np.pi),
            "score": float(truth_score),
            "hits": truth_hits,
            "rank": rank_truth + 1,
            "rank_pct": float((rank_truth + 1) / n_cand * 100),
        },
        "null_score_expectation": null_score_exp,
        "score_min": float(scores.min()),
        "score_max": float(scores.max()),
        "score_median": float(np.median(scores)),
        "top_20": [{"rank": r+1, "score": float(scores[i]), "hits": int(hit_counts[i]),
                    "qa_dist_deg": float(qa_dist[i]),
                    "om_dist_deg": float(om_dist[i]),
                    "om_mag_dps": float(np.linalg.norm(om_pass[i]) * 180 / np.pi),
                    "is_truth": bool(i == truth_idx)}
                   for r, i in enumerate(top_idx)],
    }
    with open(OUT / "summary.json", "w") as f:
        json.dump(summary, f, indent=2)
    print(f"Saved: {OUT / 'summary.json'}")
    return summary


if __name__ == "__main__":
    main()
