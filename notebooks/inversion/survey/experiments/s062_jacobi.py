"""s062 — Jacobi-elliptic closed-form omega(t) validation across the post-fix m048 cohort.

Validates the new lib.jacobi_propagator against cached truth quaternions
(generated by the post-fix DOP853 propagator) and the fresh DOP853 baseline.

Diagnostics per seed:
- omega rel max err vs DOP853 (component-wise norm / |omega0|)
- 2T conservation in Jacobi output (std/mean)
- L² conservation in Jacobi output (std/mean)
- q max diff vs cached truth (antipode-absorbing) — uses hybrid-q path
- q max diff vs fresh DOP853 (antipode-absorbing)
- regime (A or B)
- |omega|, polhode discriminant
"""
from __future__ import annotations

import sys
import time
from pathlib import Path
import json

import numpy as np

PROJECT_ROOT = Path("/home/girish/projects/lcas_v1.0")
sys.path.insert(0, str(PROJECT_ROOT / "notebooks/inversion/survey"))
sys.path.insert(0, str(PROJECT_ROOT))

from lib.hifi_render import _build_model
from lib.jacobi_propagator import omega_jacobi, propagate_jacobi, _eigendecompose_inertia
from src.dynamics.attitude_propagator import propagate_attitude


def antipode_diff(q_a: np.ndarray, q_b: np.ndarray) -> float:
    return float(min(
        np.max(np.linalg.norm(q_a - q_b, axis=1)),
        np.max(np.linalg.norm(q_a + q_b, axis=1)),
    ))


def main():
    out_dir = PROJECT_ROOT / "notebooks/inversion/survey/results/s062"
    out_dir.mkdir(parents=True, exist_ok=True)

    print("loading model + inertia eigendecomposition", flush=True)
    _, I = _build_model()
    I_pa, R_pa = _eigendecompose_inertia(I)
    inertia_meta = {
        "inertia_body": I.tolist(),
        "diagonal_in_body_frame": bool(np.allclose(I, np.diag(np.diag(I)), atol=1e-12)),
        "I_principal_ascending": I_pa.tolist(),
        "R_pa_body_columns_are_principal_axes": R_pa.tolist(),
    }
    (out_dir / "inertia_principal_axes.json").write_text(json.dumps(inertia_meta, indent=2))
    print(f"  -> {out_dir / 'inertia_principal_axes.json'}", flush=True)
    print(f"  diagonal in body frame: {inertia_meta['diagonal_in_body_frame']}", flush=True)
    print(f"  I principal (ascending): {I_pa}", flush=True)

    traj_dir = PROJECT_ROOT / "notebooks/inversion/survey/data/trajectories"
    seed_files = sorted(traj_dir.glob("traj_seed*.npz"))
    print(f"\nvalidating against {len(seed_files)} cached trajectories", flush=True)

    rows = []
    t_dop_total = 0.0
    t_jac_total = 0.0
    t_omega_total = 0.0

    for f in seed_files:
        seed = int(f.stem.replace("traj_seed", ""))
        d = np.load(f)
        q0 = d["q0_wxyz"]
        w0 = d["omega0_rad"]
        times = d["observation_times"]
        q_truth = d["quaternions"]

        # DOP853 baseline (fresh)
        t0 = time.time()
        q_dop, w_dop = propagate_attitude(q0, w0, times, "tumbling", I)
        t_dop = time.time() - t0
        t_dop_total += t_dop

        # omega closed form
        t0 = time.time()
        w_jac, info = omega_jacobi(times, w0, I)
        t_omega = time.time() - t0
        t_omega_total += t_omega

        # hybrid q via solve_ivp with closed-form omega
        t0 = time.time()
        q_jac, _ = propagate_jacobi(q0, w0, I, times, q_rtol=1e-12, q_atol=1e-14)
        t_jac = time.time() - t0
        t_jac_total += t_jac

        # diagnostics
        w0_mag = float(np.linalg.norm(w0))
        dw_rel = float(np.max(np.linalg.norm(w_jac - w_dop, axis=1)) / w0_mag)
        twoT = np.einsum("ni,ij,nj->n", w_jac, I, w_jac)
        L2 = np.einsum("ni,ni->n", w_jac @ I, w_jac @ I)
        twoT_drift = float(np.std(twoT) / np.mean(twoT))
        L2_drift = float(np.std(L2) / np.mean(L2))

        dq_truth = antipode_diff(q_jac, q_truth)
        dq_dop = antipode_diff(q_jac, q_dop)

        rows.append({
            "seed": seed,
            "regime": info["regime"],
            "omega_mag_dps": float(d["omega_mag_dps"]),
            "omega_rel_err": dw_rel,
            "twoT_drift": twoT_drift,
            "L2_drift": L2_drift,
            "q_vs_truth": dq_truth,
            "q_vs_dop": dq_dop,
            "m_k_sq": float(info["m"]),
            "t_dop_ms": t_dop * 1000,
            "t_jac_ms": t_jac * 1000,
            "t_omega_ms": t_omega * 1000,
        })

        if seed % 10 == 0:
            print(f"  seed {seed:3d} regime {info['regime']} |w|={float(d['omega_mag_dps']):.3f} dps "
                  f"omega_err={dw_rel:.2e} q_err={dq_truth:.2e}", flush=True)

    # Aggregate
    arr_omega = np.array([r["omega_rel_err"] for r in rows])
    arr_q_truth = np.array([r["q_vs_truth"] for r in rows])
    arr_q_dop = np.array([r["q_vs_dop"] for r in rows])
    arr_twoT = np.array([r["twoT_drift"] for r in rows])
    arr_L2 = np.array([r["L2_drift"] for r in rows])
    regimes = [r["regime"] for r in rows]

    summary = {
        "n_seeds": len(rows),
        "regime_A_count": regimes.count("A"),
        "regime_B_count": regimes.count("B"),
        "omega_rel_err_max": float(arr_omega.max()),
        "omega_rel_err_median": float(np.median(arr_omega)),
        "q_vs_truth_max": float(arr_q_truth.max()),
        "q_vs_truth_median": float(np.median(arr_q_truth)),
        "q_vs_dop_max": float(arr_q_dop.max()),
        "twoT_drift_max": float(arr_twoT.max()),
        "L2_drift_max": float(arr_L2.max()),
        "wall_total": {
            "dop_s": t_dop_total,
            "jacobi_hybrid_s": t_jac_total,
            "omega_closed_form_s": t_omega_total,
        },
        "wall_per_seed_ms": {
            "dop": t_dop_total / len(rows) * 1000,
            "jacobi_hybrid": t_jac_total / len(rows) * 1000,
            "omega_closed_form": t_omega_total / len(rows) * 1000,
        },
        "speedup_omega_only": t_dop_total / t_omega_total,
        "gate_omega_err_max_under_1e_8": bool(arr_omega.max() < 1e-8),
        "gate_q_vs_truth_max_under_1e_9": bool(arr_q_truth.max() < 1e-9),
        "gate_twoT_drift_under_1e_12": bool(arr_twoT.max() < 1e-12),
        "gate_L2_drift_under_1e_12": bool(arr_L2.max() < 1e-12),
    }

    print("\n" + "=" * 60, flush=True)
    print("COHORT VALIDATION SUMMARY", flush=True)
    print("=" * 60, flush=True)
    for k, v in summary.items():
        print(f"  {k}: {v}", flush=True)

    # Save
    np.savez(out_dir / "validation_per_seed.npz",
             seeds=np.array([r["seed"] for r in rows]),
             regime=np.array(regimes),
             omega_mag_dps=np.array([r["omega_mag_dps"] for r in rows]),
             omega_rel_err=arr_omega,
             q_vs_truth=arr_q_truth,
             q_vs_dop=arr_q_dop,
             twoT_drift=arr_twoT,
             L2_drift=arr_L2,
             m_k_sq=np.array([r["m_k_sq"] for r in rows]))
    print(f"\nSaved: {out_dir / 'validation_per_seed.npz'}", flush=True)

    (out_dir / "summary.json").write_text(json.dumps(summary, indent=2))
    print(f"Saved: {out_dir / 'summary.json'}", flush=True)

    # Per-seed CSV-like dump for easy inspection
    (out_dir / "per_seed.json").write_text(json.dumps(rows, indent=2))
    print(f"Saved: {out_dir / 'per_seed.json'}", flush=True)


if __name__ == "__main__":
    main()
