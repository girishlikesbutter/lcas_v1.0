"""s018a — Bright-band PAB-alignment calibration on the post-fix m048 cohort.

Pure cohort aggregation on cached truth NPZ fields — no rendering, no
propagation, no STL load. Re-validates the buggy-era "bright peak ⇒ some
body normal is PAB-aligned" claim under correct truth and produces a
calibrated bright-magnitude threshold for downstream use (s018b
peak-spacing prior, the phi-sweep IC generator, etc).

Cached inputs per seed (from `traj_seedXXX.npz`, generated by
`m048_generate_trajectories_v2.py` post-fix):
  mag_hifi        (N,)        ground-truth hi-fi magnitude
  min_ang_dist    (N,)        min over the 10 face groups of angle(n_g, pab_body)
  best_group      (N,)        argmin face-group index per epoch
  group_frac_flux (10, N)     fractional flux per group per epoch
  hifi_peak_epochs (P,)       pre-detected peak indices on -mag_hifi

Group order (from the m048 cohort summary):
  ['+X', '-X', '+Y', '-Y', '+Z', '-Z', '+WD', '-WD', '+ED', '-ED']

Outputs:
  results/s018a/calibration.npz        per-seed + cohort arrays
  results/s018a/summary.json           decision-grade scalars + threshold
  results/s018a/p_align_vs_mag.png     P(min_ang < {1,3,5,10}°) vs mag
  results/s018a/group_dominance.png    spec-event count by group, all-cohort
  results/s018a/per_seed_bright_count.png  bright-peak count per seed
"""

import json
import sys
import time
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np

ROOT = Path(__file__).resolve().parents[1]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))
from lib.traj_load import list_seeds, load_truth  # noqa: E402

OUT_DIR = ROOT / "results" / "s018a"
OUT_DIR.mkdir(parents=True, exist_ok=True)

GROUP_NAMES = ["+X", "-X", "+Y", "-Y", "+Z", "-Z", "+WD", "-WD", "+ED", "-ED"]
GROUP_AREAS_M2 = [97.3, 97.3, 16.93, 16.93, 22.75, 22.75, 9.8, 9.8, 9.8, 9.8]

MAG_BINS = [6.0, 7.0, 8.0, 9.0, 10.0, 11.0, 12.0, 13.0]
ANG_THRESHOLDS_DEG = [1.0, 3.0, 5.0, 10.0]
SPEC_ANG_DEG = 5.0  # canonical "PAB-aligned" criterion for spec event


def main():
    t0 = time.perf_counter()
    seeds = list_seeds()
    print(f"s018a — bright-band calibration over {len(seeds)} post-fix m048 seeds")

    pooled_mag = []
    pooled_min_ang = []
    pooled_best_grp = []
    pooled_seed = []
    pooled_at_peak = []  # 1 if epoch is in hifi_peak_epochs else 0

    per_seed = {
        "seed": [],
        "n_epochs": [],
        "mag_min": [],
        "mag_median": [],
        "n_peaks_pre_detected": [],
        "n_bright_lt8": [],
        "n_bright_lt9": [],
        "n_bright_lt10": [],
        "n_bright_lt11": [],
        "n_specaligned_lt5": [],   # any epoch with min_ang_dist < 5°
        "n_specaligned_lt3": [],
        "n_specaligned_lt1": [],
        "best_group_at_peak_hist": [],  # 10 floats summing to peak count
    }

    for seed in seeds:
        d = load_truth(seed)
        mag = d["mag_hifi"]
        mad = d["min_ang_dist"]
        bg = d["best_group"]
        peaks = d["hifi_peak_epochs"]

        n = mag.shape[0]
        at_peak = np.zeros(n, dtype=bool)
        at_peak[peaks] = True

        pooled_mag.append(mag)
        pooled_min_ang.append(mad)
        pooled_best_grp.append(bg)
        pooled_seed.append(np.full(n, seed, dtype=np.int32))
        pooled_at_peak.append(at_peak)

        per_seed["seed"].append(int(seed))
        per_seed["n_epochs"].append(int(n))
        per_seed["mag_min"].append(float(mag.min()))
        per_seed["mag_median"].append(float(np.median(mag)))
        per_seed["n_peaks_pre_detected"].append(int(len(peaks)))
        per_seed["n_bright_lt8"].append(int((mag < 8.0).sum()))
        per_seed["n_bright_lt9"].append(int((mag < 9.0).sum()))
        per_seed["n_bright_lt10"].append(int((mag < 10.0).sum()))
        per_seed["n_bright_lt11"].append(int((mag < 11.0).sum()))
        per_seed["n_specaligned_lt5"].append(int((mad < 5.0).sum()))
        per_seed["n_specaligned_lt3"].append(int((mad < 3.0).sum()))
        per_seed["n_specaligned_lt1"].append(int((mad < 1.0).sum()))
        # group histogram at pre-detected peaks
        hist = np.zeros(10, dtype=np.int64)
        if len(peaks) > 0:
            for g in bg[peaks]:
                hist[int(g)] += 1
        per_seed["best_group_at_peak_hist"].append(hist.tolist())

    pooled_mag = np.concatenate(pooled_mag)
    pooled_min_ang = np.concatenate(pooled_min_ang)
    pooled_best_grp = np.concatenate(pooled_best_grp)
    pooled_seed = np.concatenate(pooled_seed)
    pooled_at_peak = np.concatenate(pooled_at_peak)
    n_total = pooled_mag.shape[0]

    # P(min_ang_dist < ang_thr | mag < mag_bin) — cohort-wide
    p_align = np.zeros((len(MAG_BINS), len(ANG_THRESHOLDS_DEG)))
    n_below_mag = np.zeros(len(MAG_BINS), dtype=np.int64)
    for i, B in enumerate(MAG_BINS):
        m = pooled_mag < B
        n_below_mag[i] = int(m.sum())
        if n_below_mag[i] == 0:
            continue
        for j, A in enumerate(ANG_THRESHOLDS_DEG):
            p_align[i, j] = float(((pooled_min_ang < A) & m).sum() / n_below_mag[i])

    # Calibrated bright threshold: largest mag bin where P(min_ang < 5°) >= 0.5
    j5 = ANG_THRESHOLDS_DEG.index(SPEC_ANG_DEG)
    passing = [i for i, B in enumerate(MAG_BINS) if p_align[i, j5] >= 0.5]
    bright_threshold_calibrated = MAG_BINS[max(passing)] if passing else None

    # Per-group spec dominance at the calibrated threshold (or fallback)
    if bright_threshold_calibrated is not None:
        spec_mask = pooled_mag < bright_threshold_calibrated
    else:
        spec_mask = pooled_min_ang < SPEC_ANG_DEG  # geometric fallback
    group_counts = np.zeros(10, dtype=np.int64)
    for g in pooled_best_grp[spec_mask]:
        group_counts[int(g)] += 1
    group_freq = group_counts / max(int(spec_mask.sum()), 1)

    # Per-group spec dominance using GEOMETRIC ground truth (min_ang < 5°)
    geo_spec_mask = pooled_min_ang < SPEC_ANG_DEG
    geo_group_counts = np.zeros(10, dtype=np.int64)
    for g in pooled_best_grp[geo_spec_mask]:
        geo_group_counts[int(g)] += 1
    geo_group_freq = geo_group_counts / max(int(geo_spec_mask.sum()), 1)

    # m096 re-test: % of seeds with ZERO ±X spec events (geometric truth)
    seeds_with_pmX_geo = 0
    for seed in seeds:
        d = load_truth(seed)
        mad = d["min_ang_dist"]
        bg = d["best_group"]
        m = mad < SPEC_ANG_DEG
        groups_seen = set(int(g) for g in bg[m]) if m.any() else set()
        if 0 in groups_seen or 1 in groups_seen:
            seeds_with_pmX_geo += 1
    pct_with_pmX = 100.0 * seeds_with_pmX_geo / len(seeds)

    # Per-seed bright count distribution at calibrated threshold
    if bright_threshold_calibrated is not None:
        per_seed_bright = np.array([
            int((load_truth(s)["mag_hifi"] < bright_threshold_calibrated).sum())
            for s in seeds
        ])
    else:
        per_seed_bright = np.array(per_seed["n_bright_lt8"])

    # === Plots ===
    # 1. P(align) vs mag bin
    fig, ax = plt.subplots(1, 1, figsize=(7, 5))
    for j, A in enumerate(ANG_THRESHOLDS_DEG):
        ax.plot(MAG_BINS, p_align[:, j], "o-", label=f"P(min_ang_dist < {A:g}°)")
    ax.axhline(0.5, ls="--", color="k", alpha=0.4, label="P=0.5")
    if bright_threshold_calibrated is not None:
        ax.axvline(
            bright_threshold_calibrated,
            ls=":", color="tab:red", alpha=0.7,
            label=f"calibrated thr = {bright_threshold_calibrated:g}",
        )
    ax.set_xlabel("brightness threshold B (epochs with mag < B)")
    ax.set_ylabel("P(min_ang_dist < ang_thr | mag < B)")
    ax.set_title(
        f"s018a — bright-band PAB-alignment calibration\n"
        f"({n_total:,} epochs across {len(seeds)} seeds, post-fix m048)"
    )
    ax.legend()
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(OUT_DIR / "p_align_vs_mag.png", dpi=120)
    plt.close(fig)

    # 2. Group dominance at spec events
    fig, axes = plt.subplots(1, 2, figsize=(13, 5), sharey=True)
    x = np.arange(10)
    axes[0].bar(x, geo_group_freq, color="tab:blue")
    axes[0].set_xticks(x)
    axes[0].set_xticklabels(GROUP_NAMES)
    axes[0].set_title(
        f"GEOMETRIC truth: best_group at min_ang_dist < {SPEC_ANG_DEG:g}°\n"
        f"(n={int(geo_spec_mask.sum()):,} epochs)"
    )
    axes[0].set_ylabel("frequency at spec event")
    axes[0].grid(True, alpha=0.3, axis="y")
    if bright_threshold_calibrated is not None:
        axes[1].bar(x, group_freq, color="tab:orange")
        axes[1].set_xticks(x)
        axes[1].set_xticklabels(GROUP_NAMES)
        axes[1].set_title(
            f"OBSERVABLE proxy: best_group at mag < {bright_threshold_calibrated:g}\n"
            f"(n={int(spec_mask.sum()):,} epochs)"
        )
        axes[1].grid(True, alpha=0.3, axis="y")
    else:
        axes[1].set_visible(False)
    fig.suptitle("s018a — face-group dominance at spec events (post-fix cohort)")
    fig.tight_layout()
    fig.savefig(OUT_DIR / "group_dominance.png", dpi=120)
    plt.close(fig)

    # 3. Per-seed bright count
    fig, ax = plt.subplots(1, 1, figsize=(8, 4))
    ax.hist(per_seed_bright, bins=np.arange(0, per_seed_bright.max() + 2) - 0.5,
            color="tab:purple", edgecolor="black")
    label = (
        f"mag < {bright_threshold_calibrated:g}"
        if bright_threshold_calibrated is not None
        else "mag < 8 (fallback)"
    )
    ax.set_xlabel(f"bright epochs per seed ({label})")
    ax.set_ylabel("# seeds")
    ax.set_title(
        f"s018a — per-seed bright-epoch count distribution\n"
        f"median = {float(np.median(per_seed_bright)):.1f}, "
        f"p10 = {float(np.percentile(per_seed_bright, 10)):.0f}, "
        f"p90 = {float(np.percentile(per_seed_bright, 90)):.0f}"
    )
    ax.grid(True, alpha=0.3)
    fig.tight_layout()
    fig.savefig(OUT_DIR / "per_seed_bright_count.png", dpi=120)
    plt.close(fig)

    # === Save artefacts ===
    npz_path = OUT_DIR / "calibration.npz"
    np.savez(
        npz_path,
        # per-epoch pooled
        pooled_mag=pooled_mag,
        pooled_min_ang=pooled_min_ang,
        pooled_best_grp=pooled_best_grp,
        pooled_seed=pooled_seed,
        pooled_at_peak=pooled_at_peak,
        # cohort tables
        mag_bins=np.array(MAG_BINS),
        ang_thresholds_deg=np.array(ANG_THRESHOLDS_DEG),
        p_align=p_align,
        n_below_mag=n_below_mag,
        # group dominance
        group_names=np.array(GROUP_NAMES),
        group_areas_m2=np.array(GROUP_AREAS_M2),
        geo_group_counts=geo_group_counts,
        geo_group_freq=geo_group_freq,
        obs_group_counts=group_counts,
        obs_group_freq=group_freq,
        # per-seed
        seeds=np.array(per_seed["seed"]),
        per_seed_bright=per_seed_bright,
        per_seed_n_bright_lt8=np.array(per_seed["n_bright_lt8"]),
        per_seed_n_bright_lt9=np.array(per_seed["n_bright_lt9"]),
        per_seed_n_bright_lt10=np.array(per_seed["n_bright_lt10"]),
        per_seed_n_bright_lt11=np.array(per_seed["n_bright_lt11"]),
        per_seed_n_specaligned_lt5=np.array(per_seed["n_specaligned_lt5"]),
        per_seed_n_specaligned_lt3=np.array(per_seed["n_specaligned_lt3"]),
        per_seed_n_specaligned_lt1=np.array(per_seed["n_specaligned_lt1"]),
        per_seed_n_peaks_pre_detected=np.array(per_seed["n_peaks_pre_detected"]),
        per_seed_best_group_at_peak_hist=np.array(per_seed["best_group_at_peak_hist"]),
    )

    summary = {
        "n_seeds": len(seeds),
        "n_epochs_total": int(n_total),
        "spec_angle_deg": float(SPEC_ANG_DEG),
        "calibrated_bright_threshold": (
            float(bright_threshold_calibrated)
            if bright_threshold_calibrated is not None
            else None
        ),
        "p_align_table": {
            f"mag<{B:g}": {
                f"p_min_ang<{A:g}deg": float(p_align[i, j])
                for j, A in enumerate(ANG_THRESHOLDS_DEG)
            }
            for i, B in enumerate(MAG_BINS)
        },
        "n_below_mag": {f"mag<{B:g}": int(n_below_mag[i]) for i, B in enumerate(MAG_BINS)},
        "geo_spec_event_count": int(geo_spec_mask.sum()),
        "geo_group_freq": {GROUP_NAMES[g]: float(geo_group_freq[g]) for g in range(10)},
        "geo_group_areas_m2": {GROUP_NAMES[g]: float(GROUP_AREAS_M2[g]) for g in range(10)},
        "observable_spec_event_count": int(spec_mask.sum()),
        "obs_group_freq": {GROUP_NAMES[g]: float(group_freq[g]) for g in range(10)},
        "m096_retest": {
            "claim": "buggy-era m096: 87% of seeds lack bright +-X constraints",
            "spec_criterion": f"min_ang_dist < {SPEC_ANG_DEG:g}deg (geometric ground truth, any epoch)",
            "n_seeds_with_pmX_spec": int(seeds_with_pmX_geo),
            "pct_with_pmX_spec": float(pct_with_pmX),
            "pct_lacking_pmX_spec": float(100.0 - pct_with_pmX),
        },
        "per_seed_bright_count": {
            "median": float(np.median(per_seed_bright)),
            "p10": float(np.percentile(per_seed_bright, 10)),
            "p90": float(np.percentile(per_seed_bright, 90)),
            "min": int(per_seed_bright.min()),
            "max": int(per_seed_bright.max()),
            "n_with_zero": int((per_seed_bright == 0).sum()),
            "n_with_lt3": int((per_seed_bright < 3).sum()),
        },
        "wall_seconds": float(time.perf_counter() - t0),
    }
    with open(OUT_DIR / "summary.json", "w") as f:
        json.dump(summary, f, indent=2)

    # === Console report ===
    print("")
    print(f"=== s018a calibration summary (wall {summary['wall_seconds']:.1f} s) ===")
    print(f"pooled epochs: {n_total:,}")
    print("")
    print("P(min_ang_dist < ang_thr | mag < B):")
    header = "  mag<B    n      " + "  ".join(f"<{A:>3g}°" for A in ANG_THRESHOLDS_DEG)
    print(header)
    for i, B in enumerate(MAG_BINS):
        row = f"  {B:>5g}  {n_below_mag[i]:>6d}    " + "  ".join(
            f"{p_align[i, j]:.3f}" for j in range(len(ANG_THRESHOLDS_DEG))
        )
        print(row)
    print("")
    if bright_threshold_calibrated is not None:
        print(
            f"Calibrated bright threshold: mag < {bright_threshold_calibrated:g} "
            f"(P(min_ang<{SPEC_ANG_DEG:g}°) >= 0.5)"
        )
    else:
        print(
            f"NO calibrated threshold passes 0.5 — P(min_ang<{SPEC_ANG_DEG:g}°) "
            f"never reaches 0.5 even at the tightest mag bin."
        )
    print("")
    print(f"Per-group spec dominance (geometric, min_ang_dist < {SPEC_ANG_DEG:g}°):")
    for g in np.argsort(-geo_group_freq):
        print(
            f"  {GROUP_NAMES[g]:>4s}  area={GROUP_AREAS_M2[g]:>5.1f} m²  "
            f"freq={geo_group_freq[g]:.3f}  count={geo_group_counts[g]}"
        )
    print("")
    print(
        f"m096 re-test: {summary['m096_retest']['pct_lacking_pmX_spec']:.0f}% of "
        f"{len(seeds)} seeds LACK any ±X spec event (min_ang_dist<{SPEC_ANG_DEG:g}°). "
        f"Buggy-era claim was 87%."
    )
    print("")
    print(
        f"Per-seed bright count (mag < calibrated threshold): "
        f"median {summary['per_seed_bright_count']['median']:.1f}, "
        f"p10 {summary['per_seed_bright_count']['p10']:.0f}, "
        f"p90 {summary['per_seed_bright_count']['p90']:.0f}, "
        f"n_seeds_with_zero={summary['per_seed_bright_count']['n_with_zero']}, "
        f"n_seeds_with_lt3={summary['per_seed_bright_count']['n_with_lt3']}"
    )
    print("Saved:")
    print(f"  {OUT_DIR / 'calibration.npz'}")
    print(f"  {OUT_DIR / 'summary.json'}")
    print(f"  {OUT_DIR / 'p_align_vs_mag.png'}")
    print(f"  {OUT_DIR / 'group_dominance.png'}")
    print(f"  {OUT_DIR / 'per_seed_bright_count.png'}")


if __name__ == "__main__":
    main()
